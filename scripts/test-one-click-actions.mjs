import assert from 'node:assert/strict';
import fs from 'node:fs';

const source = fs.readFileSync(new URL('../src/content.js', import.meta.url), 'utf8');
const question = source.slice(source.indexOf('const render ='), source.indexOf('let checkinPrepared'));
const checkin = source.slice(source.indexOf('let checkinPrepared'), source.indexOf('let timer;'));

assert.match(question, /oneClick\.textContent = '一键答题'/);
assert.match(question, /oneClick\.addEventListener\('click'/);
assert.match(question, /DailyQuestionPage\.getState\(\)/);
assert.match(source, /const runQuestionAction = async/);
const answerAction = source.slice(source.indexOf('const runQuestionAction'), source.indexOf('chrome.runtime.onMessage.addListener'));
assert.match(answerAction, /waitForStableQuestionSnapshot/);
assert.match(answerAction, /const questionReadyTimeoutMs = actionId \? QUESTION_READY_TIMEOUT_MS : REMOTE_ACTION_TIMEOUT_MS/);
assert.match(answerAction, /const lookupResponse = await bridge\.send\(ExtensionProtocol\.MESSAGE_TYPES\.LOOKUP_QUESTION/);
assert.match(answerAction, /const actionKey = `\$\{snapshot\.question\}:\$\{lookupAnswerText\}`/);
assert.match(answerAction, /if \(actionKey === answerActionKey\) \{ failRemote\('duplicate-action'\); status\.textContent = '已一键答题，等待站点结果'; return; \}/);
assert.match(answerAction, /const submitResult = await waitForQuestionSubmit\(snapshot\.question, lookupOptionTexts, lookupAnswerText\)/);
assert.match(answerAction, /if \(!submitResult\.ok\) \{/);
assert.match(answerAction, /question-not-ready/);
assert.match(answerAction, /question-changed-or-unavailable/);
assert.match(source, /const waitForQuestionSubmit = async/);
assert.match(source, /QUESTION_SUBMIT_WAIT_MS/);
assert.match(source, /const waitForCheckinSubmit = async/);
assert.match(source, /CHECKIN_SUBMIT_WAIT_MS/);
assert.match(source, /reason: 'submit-timeout'/);
assert.match(source, /const current = DailyQuestionPage\.findSubmit\(\) \|\| button/, 'submission must use the current React-rendered button');
assert.doesNotMatch(source, /current !== button/, 'submission must not fail only because React replaced the button node');
assert.match(source, /current\.isConnected/, 'submission must reject detached controls');
assert.match(source, /currentQuestion !== questionKey/);
assert.match(source, /currentOptions\.map\(DailyQuestionPage\.clean\)\.join\('\\u0001'\) !== optionTexts\.join\('\\u0001'\)/);
assert.match(source, /DailyQuestionPage\.findSubmit\(\)/);
assert.doesNotMatch(source, /findSelectedOption\(document, currentOptions\) === matching\[0\] && siteSubmit/);
assert.match(source, /const selected = DailyQuestionPage\.findSelectedOption\(document, currentOptions\)/, 'live site selection must be re-read');
assert.match(source, /if \(selected === matching\[0\] && siteSubmit && !siteSubmit\.disabled\) return \{ ok: true, button: siteSubmit \}/, 'only the uniquely selected correct option plus enabled submit may pass');
assert.match(source, /p3a-answer-\*/, 'extension answer markers must not be used as site selection');
assert.match(source, /const questionResult = DailyQuestionPage\.findQuestion\(\)/, 'question must be re-read while waiting');
assert.doesNotMatch(question, /if \(!submitResult\.ok\)/, 'render slice should not be treated as the submit gate');
assert.match(answerAction, /const siteSubmit = DailyQuestionPage\.findSubmit\(\)/, 'submit must be re-found after React readiness wait');
assert.match(answerAction, /clickVisibleQuestionSubmit\(siteSubmit\)/, 'only the live visible site button may be clicked');
assert.match(source, /submit-button-stale-or-unavailable/);
assert.match(source, /已触发官网提交，等待结果/);
const answerActionKeyRecord = answerAction.indexOf('answerActionKey = actionKey');
const submitClickRecord = answerAction.indexOf('clickVisibleQuestionSubmit(siteSubmit)');
assert(answerActionKeyRecord > submitClickRecord, 'answerActionKey must be recorded after successful submit click');
assert.match(answerAction, /已一键答题，等待站点结果/);
assert.match(answerAction, /currentOptionText\.join\('\\u0001'\) !== lookupOptionTexts\.join\('\\u0001'\)/, 'answer must reject changed option text/order');
assert.match(answerAction, /currentOptions\.filter\(\(node\) => DailyQuestionPage\.clean\(node\) === lookupAnswerText\)/, 'answer must match current option text, not cached index');
assert.match(answerAction, /matching\.length !== 1/, 'answer must reject ambiguous target text');
assert.match(question, /answerActionKey = null/);
assert.match(question, /const result = \(await bridge\.send\(ExtensionProtocol\.MESSAGE_TYPES\.LOOKUP_QUESTION/);
assert.match(question, /!result \|\| result\.status === 'unmatched' \|\| result\.status === 'ambiguous'/);
assert.match(question, /未找到已启用的官网提交按钮，未提交/);

assert.match(checkin, /oneClick\.textContent = '一键签到'/);
assert.match(checkin, /oneClick\.addEventListener\('click'/);
const checkinAction = checkin.slice(checkin.indexOf("oneClick.addEventListener('click'"));
const checkinOptionClick = checkinAction.indexOf('current.click()');
const checkinSubmitLookup = checkinAction.indexOf('await waitForCheckinSubmit()');
const checkinSubmitClick = checkinAction.indexOf('submit.click()');
assert(checkinOptionClick >= 0 && checkinSubmitLookup > checkinOptionClick && checkinSubmitClick > checkinSubmitLookup, 'checkin submit must be looked up after option preparation');
assert.match(checkinAction, /if \(!submit\) \{ failRemote\('submit-not-found'\); status\.textContent = '未找到站点签到按钮，未提交'; return; \}/);
assert.match(checkinAction, /if \(!CheckinState\.reconcile\(checkinPrepared, location\.href, current\)\) \{ current\.click\(\)/);
assert.match(checkinAction, /checkinActionKey = key/);
assert.match(checkinAction, /catch \{ checkinActionKey = null;/, 'checkin failure must remain retryable');
assert.doesNotMatch(checkinAction, /DailyCheckinPage\.nodeSignature/, 'checkin must use the shared state signature helper');

assert.doesNotMatch(source, /\? \/答对\|回答正确\//, 'question success must not accept bare answer text');
assert.doesNotMatch(source, /获得奖励|奖励\.\*米/, 'success must not accept generic reward text');
assert.match(source, /finishRemoteAction\(actionId, 'question', 'failed'/, 'question early returns must report failure');
assert.match(source, /finishRemoteAction\(actionId, 'checkin', 'failed'/, 'checkin early returns must report failure');
assert.match(source, /finishRemoteAction\(actionId, action, 'success', 'completed'/, 'success must be reported from completed/explicit result wait');
assert.match(source, /const checkinToastId = 'p3a-checkin-complete-toast'/);
assert.match(source, /const showCheckinToast = \(message = '签到完成'\)/);
assert.match(source, /toast\.textContent = message/);
assert.match(source, /setTimeout\(\(\) => \{ toast\.remove\(\); \}, 3000\)/);
assert.match(source, /action === 'question' \? '答题完成' : '签到完成'/);
assert.match(source, /actionId, action, status, reason/, 'ACTION_RESULT payload must carry actionId');
assert.match(source, /if \(!actionId\) \{[\s\S]*?if \(status === 'success'\) showCheckinToast\(toastMessage\);[\s\S]*?return;/, 'local actions must clean up and show success toast without reporting ACTION_RESULT');
assert.match(checkinAction, /await waitForRemoteResult\('checkin', remoteActionId, status\)/, 'page one-click check-in must await the site result without a remote action id');
const confirmAction = checkin.slice(checkin.indexOf("confirm.addEventListener('click'"));
assert.match(confirmAction, /await waitForRemoteResult\('checkin', remoteActionId, status\)/, 'manual confirm check-in must await the site result');
assert.match(source, /state === 'requires-login'[\s\S]*?finishRemoteAction\(actionId, action, 'failed'/, 'site failure must finish as failed');
const finish = source.slice(source.indexOf('const finishRemoteAction'), source.indexOf('const waitForRemoteResult'));
assert.doesNotMatch(finish, /status === 'failed'[\s\S]*?showCheckinToast/, 'failed local actions must not show a success toast');

assert.doesNotMatch(source, /(?:^|\W)(?:fetch|XMLHttpRequest)\s*\(/, 'content actions must not call remote APIs');
console.log('one-click action tests passed.');
