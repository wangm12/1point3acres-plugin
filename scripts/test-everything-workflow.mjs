#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';

const read = (path) => fs.readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const html = read('src/popup.html');
const popup = read('src/popup.js');
const worker = read('src/service-worker.js');
assert.match(html, /id="run-everything"/);
assert.match(html, /id="run-checkin"/);
assert.match(html, /id="run-question"/);
assert.match(html, /id="alert-action-btn"/);
assert.doesNotMatch(html, /打开每日答题|打开每日签到/);
assert.match(popup, /sendRuntimeMessage\(ExtensionProtocol\.MESSAGE_TYPES\.RUN_ONE_CLICK/);
assert.match(worker, /const RUNTIME_STORAGE_KEY = 'p3a-runtime-v1'/);
assert.match(worker, /const runtimeStorage = chrome\.storage\.session \|\| chrome\.storage\.local/);
assert.match(worker, /const coordinatorStart = async/);
assert.match(worker, /const coordinatorActionResult = async/);
assert.match(worker, /const coordinatorFinalize = async/);
assert.match(worker, /runtimeState\.run\.stage = 'checkin'/);
assert.match(worker, /reason: 'completed-checkin-advances-to-question'/);
assert.match(worker, /closeActionTabSafely\(pending\.tabId, pending\)/);
assert.match(worker, /await notifyCheckinCompletedOnce\(pending\.workflowId\)/);
assert.match(worker, /notifications\.create/);
assert.match(worker, /sendResponse\(reply\);\s*if \(reply\?\.accepted === true && reply\?\.finalize\)/s, 'ACK must be sent before finalize');
assert.match(worker, /coordinatorFinalize\(reply\.finalize\)/);
assert.match(worker, /finalizationPending: true/);
assert.match(worker, /workflow\.stage = 'question'/);
assert.match(worker, /runtimeState\.run\.transition = 'question'/);
assert.match(worker, /stage: 'question'/);
assert.match(worker, /workflow-stage-mismatch/);
assert.match(worker, /storage\.session/);
assert.match(worker, /status: 'running'/);
assert.match(worker, /question-tab-created/);
console.log('Everything workflow tests passed.');
